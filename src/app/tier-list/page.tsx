'use client';

import React from 'react';
import { useHeroes } from '@/hooks/useHeroes';

type Tier = 'S' | 'A' | 'B' | 'C';

const standardLanes = ['EXP Lane', 'Gold Lane', 'Mid Lane', 'Jungler', 'Roamer'];
const laneColors: Record<string, string> = {
  'EXP Lane': 'border-orange-400/30 bg-orange-950/30 text-orange-200',
  'Gold Lane': 'border-yellow-400/30 bg-yellow-950/30 text-yellow-200',
  'Mid Lane': 'border-purple-400/30 bg-purple-950/30 text-purple-200',
  Jungler: 'border-emerald-400/30 bg-emerald-950/30 text-emerald-200',
  Roamer: 'border-cyan-400/30 bg-cyan-950/30 text-cyan-200',
  Unassigned: 'border-slate-400/30 bg-slate-900 text-slate-200',
};
const tierOrder: Tier[] = ['S', 'A', 'B', 'C'];
const tierStyles: Record<Tier, { label: string; color: string; cell: string }> = {
  S: { label: 'Top 20%', color: 'border-rose-400/40 bg-rose-950/50 text-rose-200', cell: 'bg-rose-950/10' },
  A: { label: 'Next 30%', color: 'border-sky-400/40 bg-sky-950/50 text-sky-200', cell: 'bg-sky-950/10' },
  B: { label: 'Next 30%', color: 'border-emerald-400/40 bg-emerald-950/50 text-emerald-200', cell: 'bg-emerald-950/10' },
  C: { label: 'Bottom 20%', color: 'border-slate-400/30 bg-slate-800/70 text-slate-300', cell: 'bg-slate-900/40' },
};

function tierForPosition(index: number, count: number): Tier {
  const position = index / count;
  if (position < 0.2) return 'S';
  if (position < 0.5) return 'A';
  if (position < 0.8) return 'B';
  return 'C';
}

export default function TierListPage() {
  const { heroes, loading, error, reload, source, period, rankingWarning, updatedAt } = useHeroes();
  const knownLanes = new Set(standardLanes);
  const additionalLanes = Array.from(new Set(heroes.flatMap((hero) => hero.lanes).filter((lane) => !knownLanes.has(lane)))).sort();
  const hasUnassignedHeroes = heroes.some((hero) => hero.lanes.length === 0);
  const lanes = [...standardLanes, ...additionalLanes, ...(hasUnassignedHeroes ? ['Unassigned'] : [])];
  const laneTiers = new Map<string, Record<Tier, typeof heroes>>();
  const laneUnranked = new Map<string, typeof heroes>();

  for (const lane of lanes) {
    const laneHeroes = heroes
      .filter((hero) => lane === 'Unassigned' ? hero.lanes.length === 0 : hero.lanes.includes(lane))
      .slice()
      .sort((left, right) => (left.rank ?? Number.MAX_SAFE_INTEGER) - (right.rank ?? Number.MAX_SAFE_INTEGER));
    const rankedHeroes = laneHeroes.filter((hero) => hero.rank !== undefined);
    const groups: Record<Tier, typeof heroes> = { S: [], A: [], B: [], C: [] };
    rankedHeroes.forEach((hero, index) => groups[tierForPosition(index, rankedHeroes.length)].push(hero));
    laneTiers.set(lane, groups);
    laneUnranked.set(lane, laneHeroes.filter((hero) => hero.rank === undefined));
  }

  return (
    <main className="mx-auto max-w-7xl space-y-4 p-3 font-mono sm:p-6">
      <header className="space-y-2 border-b border-white/10 pb-3">
        <div className="flex flex-wrap items-end justify-between gap-2">
          <div>
            <h1 className="text-xl font-extrabold uppercase text-white sm:text-2xl">Official tier list by lane</h1>
            <p className="mt-1 text-[11px] text-slate-400">One-page view grouped by lane and tier.</p>
          </div>
          <span className="rounded-lg border border-blue-500/30 bg-blue-950/30 px-2.5 py-1 text-[9px] font-bold text-blue-200">{heroes.length} HEROES</span>
        </div>
        <p className="text-[9px] text-slate-500">{source}{period ? ' | ' + period : ''}{updatedAt ? ' | Updated ' + new Date(updatedAt).toLocaleString() : ''}</p>
        {rankingWarning ? <p role="status" className="text-xs text-amber-300">{rankingWarning}</p> : null}
        <p className="text-[9px] text-slate-500">App tiers use relative percentiles within each lane; hero order follows overall win rate from MLBB&apos;s official data, not lane-specific rankings. These tier labels are generated by this app. Heroes can appear in multiple lanes.</p>
      </header>

      {loading ? <p className="py-12 text-center text-sm text-slate-400">Loading official MLBB data...</p> : error ? (
        <div role="alert" className="rounded-xl border border-amber-500/30 bg-amber-950/20 p-4 text-amber-200">
          {error}<button type="button" onClick={reload} className="ml-3 underline">Retry</button>
        </div>
      ) : heroes.length === 0 ? <p className="py-12 text-center text-sm text-slate-400">No official ranking data is available.</p> : (
        <div className="overflow-x-auto pb-2">
          <div className="grid min-w-[980px] grid-cols-[62px_repeat(5,minmax(0,1fr))] gap-px overflow-hidden rounded-xl border border-white/10 bg-white/10" style={{ gridTemplateColumns: '62px repeat(' + lanes.length + ', minmax(0, 1fr))' }} aria-label="Tier list matrix by lane">
            <div className="flex items-center justify-center bg-[#121317] p-2 text-[9px] font-bold uppercase text-slate-500">Tier</div>
            {lanes.map((lane) => (
              <div key={'header-' + lane} className="flex min-w-0 items-center justify-between gap-1 bg-[#121317] px-2 py-2">
                <h2 className={'truncate rounded-md border px-2 py-1 text-[9px] font-extrabold uppercase sm:text-[10px] ' + (laneColors[lane] ?? laneColors.Unassigned)}>{lane}</h2>
                <span className="shrink-0 text-[8px] text-slate-500">{heroes.filter((hero) => lane === 'Unassigned' ? hero.lanes.length === 0 : hero.lanes.includes(lane)).length}</span>
              </div>
            ))}

            {tierOrder.map((tier) => (
              <React.Fragment key={tier}>
                <div className={'flex flex-col items-center justify-center gap-1 p-1 ' + tierStyles[tier].cell}>
                  <span className={'rounded-md border px-2 py-1 text-sm font-black ' + tierStyles[tier].color}>{tier}</span>
                  <span className="text-center text-[7px] uppercase leading-tight text-slate-500">{tierStyles[tier].label}</span>
                </div>
                {lanes.map((lane) => {
                  const tierHeroes = laneTiers.get(lane)?.[tier] ?? [];
                  return (
                    <div key={tier + '-' + lane} className={'min-w-0 p-1.5 ' + tierStyles[tier].cell}>
                      {tierHeroes.length === 0 ? <div className="flex h-full min-h-12 items-center justify-center text-[9px] text-slate-700">-</div> : (
                        <div className="grid grid-cols-3 gap-1 sm:grid-cols-4">
                          {tierHeroes.map((hero) => (
                            <article key={hero.id + '-' + lane} title={hero.name + ' | Overall rank #' + hero.rank + ' | Win ' + (hero.winRate ?? '-') + ' | Pick ' + (hero.pickRate ?? '-') + ' | Ban ' + (hero.banRate ?? '-')} className="flex min-w-0 flex-col items-center rounded-md border border-white/5 bg-[#111216]/80 p-1 text-center">
                              {hero.avatarUrl ? <img src={hero.avatarUrl} alt={hero.name} loading="lazy" className="h-7 w-7 rounded-full border border-white/10 bg-slate-900 object-cover sm:h-8 sm:w-8" /> : <div className="flex h-7 w-7 items-center justify-center rounded-full bg-slate-800 text-[8px] text-slate-300 sm:h-8 sm:w-8">{hero.name.slice(0, 2)}</div>}
                              <span className="mt-0.5 w-full truncate text-[7px] font-semibold text-slate-200 sm:text-[8px]">{hero.name}</span>
                              <span className="text-[7px] font-bold text-emerald-300">{hero.winRate ?? '-'}</span>
                            </article>
                          ))}
                        </div>
                      )}
                    </div>
                  );
                })}
              </React.Fragment>
            ))}

            {lanes.some((lane) => (laneUnranked.get(lane)?.length ?? 0) > 0) && <>
              <div className="flex items-center justify-center bg-slate-900 p-1 text-center text-[8px] font-bold uppercase text-slate-400">No rank</div>
              {lanes.map((lane) => {
                const unrankedHeroes = laneUnranked.get(lane) ?? [];
                return <div key={'unranked-' + lane} className="bg-slate-900/60 p-1.5">
                  {unrankedHeroes.length ? <div className="grid grid-cols-3 gap-1 sm:grid-cols-4">{unrankedHeroes.map((hero) => <span key={hero.id + '-' + lane} title={hero.name + ' | No official rank'} className="truncate rounded-md bg-[#111216] px-1 py-1.5 text-center text-[7px] text-slate-400">{hero.name}</span>)}</div> : <div className="flex min-h-8 items-center justify-center text-[9px] text-slate-700">-</div>}
                </div>;
              })}
            </>}
          </div>
        </div>
      )}
    </main>
  );
}
